(function() {
    const urlParams = new URLSearchParams(window.location.search);
    const lang = urlParams.get('lang') || currentLanguage;
    setLanguage(lang);
})();

function setLanguage(lang) {
    currentLanguage = lang;
    console.log(currentLanguage);
    
    // translate all elements with data-i18n attribute
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        
        // Check if key exists in the external dictionary file
        if (dictionary[lang] && dictionary[lang][key]) {
            element.innerHTML = dictionary[lang][key];
        }
    });

    // update active language select button styles
    document.getElementById('btn-en').classList.toggle('active', currentLanguage === 'en');

    // update domain-count pill if it exists
    const domainCountPill = document.getElementById('domain-count');
    if (domainCountPill && window.domainManager) {
        const count = window.domainManager.count();
        domainCountPill.innerHTML = count;
        console.log('Updated domain count pill:', count);
    }

    // check if url contains lang parameter, if not, add it or change it
    const url = new URL(window.location);
    url.searchParams.set('lang', currentLanguage);
    window.history.replaceState({}, '', url);
}
